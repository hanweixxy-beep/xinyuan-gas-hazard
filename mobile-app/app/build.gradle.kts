val releaseKeystoreProperties = Properties()
val releaseKeystorePropertiesFile = rootProject.file("signing/release-keystore.properties")
if (releaseKeystorePropertiesFile.exists()) {
    releaseKeystorePropertiesFile.inputStream().use { releaseKeystoreProperties.load(it) }
}

fun releaseSigningProperty(name: String): String? =
    (releaseKeystoreProperties[name] as? String)?.takeIf { it.isNotBlank() }
        ?: System.getenv("XINYUAN_${name.uppercase()}")

val releaseStoreFile = releaseSigningProperty("storeFile")
val releaseStorePassword = releaseSigningProperty("storePassword")
val releaseKeyAlias = releaseSigningProperty("keyAlias")
val releaseKeyPassword = releaseSigningProperty("keyPassword")
val hasReleaseSigningConfig = listOf(
    releaseStoreFile,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword
).all { !it.isNullOrBlank() }

